const _kLocaleStorageKey = '__locale_key__';
const _kLocaleUserPickedKey = '__locale_user_picked__';

class FFLocalizations {
  FFLocalizations(this.locale);

  final Locale locale;

  static FFLocalizations of(BuildContext context) =>
      Localizations.of<FFLocalizations>(context, FFLocalizations)!;

  static List<String> languages() =>
      ['en', 'ar', 'ru', 'ky', 'fr', 'ur', 'pt'];

  static late SharedPreferences _prefs;
  static Future initialize() async =>
      _prefs = await SharedPreferences.getInstance();
  static Future storeLocale(String locale) async {
    await _prefs.setString(_kLocaleStorageKey, locale);
    await _prefs.setBool(_kLocaleUserPickedKey, true);
  }

  static Locale? getStoredLocale() {
    final locale = _prefs.getString(_kLocaleStorageKey);
    return locale != null && locale.isNotEmpty ? createLocale(locale) : null;
  }

  static bool get hasUserPickedLocale =>
      _prefs.getBool(_kLocaleUserPickedKey) ?? false;

  /// Maps the device locale to a supported app locale, or English if unsupported.
  static Locale resolveDeviceLocale([Locale? deviceLocale]) {
    final device = deviceLocale ?? PlatformDispatcher.instance.locale;
    final language = device.languageCode.toLowerCase();

    if (language == 'zh') {
      return const Locale.fromSubtags(languageCode: 'zh', scriptCode: 'Hans');
    }

    if (languages().contains(language)) {
      return Locale(language);
    }

    return const Locale('en');
  }

  /// Stored manual choice, else device locale (English when unsupported).
  static Locale resolveInitialLocale() {
    if (hasUserPickedLocale) {
      final stored = getStoredLocale();
      if (stored != null) {
        return stored;
      }
    }
    return resolveDeviceLocale();
  }

  static String localizedAppTitle(Locale? locale) =>
      FFLocalizations(locale ?? resolveInitialLocale()).getText('adm_app_title');

  String get languageCode {
    // Prefer languageCode so Locale('fr','FR') still resolves catalog key 'fr'.
    final code = locale.languageCode.toLowerCase();
    if (languages().contains(code)) return code;
    final full = locale.toString();
    return languages().contains(full) ? full : code;
  }
  String? get languageShortCode =>
      _languagesWithShortCode.contains(locale.toString())
          ? '${locale.toString()}_short'
          : null;
  int get languageIndex => languages().contains(languageCode)
      ? languages().indexOf(languageCode)
      : 0;

  String getText(String key) {
    final map = kTranslationsMap[key] ??
        kAdminTranslations[key] ??
        kEnterpriseTranslations[key] ??
        kNavTranslations[key] ??
        kUiCatalog[key] ??
        {};
    // Always resolve by ISO language code (fr, not fr_FR) so catalog keys match.
    final lang = locale.languageCode.toLowerCase();
    // Missing keys fall back to English only — never KY->RU as a normal path.
    final text = map[lang] ?? map['en'] ?? '';
    return text;
  }

  String getVariableText({
    String? enText = '',
    String? arText = '',
    String? zh_HansText = '',
    String? trText = '',
    String? urText = '',
    String? ruText = '',
    String? azText = '',
    String? kaText = '',
    String? kyText = '',
    String? frText = '',
    String? ptText = '',
  }) {
    // Prefer language code over array index so locale list changes cannot
    // throw RangeError (H-01/H-02).
    switch (languageCode) {
      case 'ar':
        return (arText != null && arText.isNotEmpty) ? arText : (enText ?? '');
      case 'ru':
        return (ruText != null && ruText.isNotEmpty) ? ruText : (enText ?? '');
      case 'ky':
        if (kyText != null && kyText.isNotEmpty) return kyText;
        return enText ?? '';
      case 'zh_Hans':
        return (zh_HansText != null && zh_HansText.isNotEmpty)
            ? zh_HansText
            : (enText ?? '');
      case 'tr':
        return (trText != null && trText.isNotEmpty) ? trText : (enText ?? '');
      case 'ur':
        return (urText != null && urText.isNotEmpty) ? urText : (enText ?? '');
      case 'fr':
        return (frText != null && frText.isNotEmpty) ? frText : (enText ?? '');
      case 'pt':
        return (ptText != null && ptText.isNotEmpty) ? ptText : (enText ?? '');
      case 'az':
        return (azText != null && azText.isNotEmpty) ? azText : (enText ?? '');
      case 'ka':
        return (kaText != null && kaText.isNotEmpty) ? kaText : (enText ?? '');
      default:
        return enText ?? '';
    }
  }

  static const Set<String> _languagesWithShortCode = {
    'ar',
    'az',
    'ca',
